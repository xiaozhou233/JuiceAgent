#ifndef __WALL
#define __WALL 0x40000000
#endif

user_regs_struct get_registers(pid_t tid) {
  user_regs_struct regs{};
  if (ptrace(PTRACE_GETREGS, tid, nullptr, &regs) == -1) {
    throw_errno("PTRACE_GETREGS on tid " + std::to_string(tid));
  }
  return regs;
}

void set_registers(pid_t tid, const user_regs_struct& regs) {
  user_regs_struct copy = regs;
  if (ptrace(PTRACE_SETREGS, tid, nullptr, &copy) == -1) {
    throw_errno("PTRACE_SETREGS on tid " + std::to_string(tid));
  }
}

void continue_tracee(pid_t tid) {
  // The last argument is the signal to deliver.  0 suppresses the SIGTRAP
  // from int3 (and the SIGSTOP from PTRACE_ATTACH).
  if (ptrace(PTRACE_CONT, tid, nullptr, nullptr) == -1) {
    throw_errno("PTRACE_CONT on tid " + std::to_string(tid));
  }
}

void wait_for_trap(pid_t tid, std::uint64_t expected_rip) {
  int status = 0;
  for (;;) {
    pid_t waited;
    do {
      waited = waitpid(tid, &status, __WALL);
    } while (waited == -1 && errno == EINTR);

    if (waited == -1) {
      throw_errno("waitpid on tid " + std::to_string(tid));
    }
    if (WIFEXITED(status)) {
      throw std::runtime_error("tracee exited with status " +
                               std::to_string(WEXITSTATUS(status)));
    }
    if (WIFSIGNALED(status)) {
      throw std::runtime_error("tracee was killed by signal " +
                               std::to_string(WTERMSIG(status)));
    }
    if (!WIFSTOPPED(status)) {
      continue;
    }

    const int signal = WSTOPSIG(status);
    if (signal == SIGTRAP) {
      // Only accept the SIGTRAP generated by our own int3.  On x86-64 RIP
      // points just past the int3 instruction at that stop.
      const user_regs_struct regs = get_registers(tid);
      if (regs.rip == expected_rip) {
        return;
      }
      throw TraceeSignalError(
          tid, signal,
          "unexpected SIGTRAP at rip=0x" + hex_string(regs.rip) +
              " (expected 0x" + hex_string(expected_rip) + ")");
    }

    const user_regs_struct regs = get_registers(tid);
    throw TraceeSignalError(tid, signal,
                            "shellcode in tracee received unexpected signal " +
                                std::to_string(signal) + " (" +
                                strsignal(signal) + ") at rip=0x" +
                                hex_string(regs.rip));
  }
}

static std::vector<pid_t> list_threads(pid_t pid) {
  const std::string directory = "/proc/" + std::to_string(pid) + "/task";
  std::error_code ec;
  std::filesystem::directory_iterator iterator(directory, ec);
  const std::filesystem::directory_iterator end;
  if (ec) {
    throw std::runtime_error("cannot list threads of pid " +
                             std::to_string(pid) + ": " + ec.message());
  }

  std::vector<pid_t> threads;
  for (; iterator != end; iterator.increment(ec)) {
    if (ec) {
      break;
    }
    const std::string name = iterator->path().filename().string();
    if (!all_digits(name)) {
      continue;
    }
    try {
      threads.push_back(static_cast<pid_t>(std::stoi(name)));
    } catch (const std::exception&) {
      continue;
    }
  }
  std::sort(threads.begin(), threads.end());
  return threads;
}

static bool attach_one_thread(pid_t tid, std::vector<pid_t>& attached) {
  if (ptrace(PTRACE_ATTACH, tid, nullptr, nullptr) == -1) {
    if (errno == ESRCH) {
      return false;  // thread exited while we were enumerating
    }
    throw_errno("PTRACE_ATTACH on tid " + std::to_string(tid));
  }

  // Record it before waiting: if waitpid fails, the thread is still attached
  // and the caller must be able to detach it.
  attached.push_back(tid);

  int status = 0;
  pid_t waited;
  do {
    waited = waitpid(tid, &status, __WALL);
  } while (waited == -1 && errno == EINTR);

  if (waited == -1) {
    throw_errno("waitpid after attaching to tid " + std::to_string(tid));
  }
  if (!WIFSTOPPED(status)) {
    throw std::runtime_error("thread " + std::to_string(tid) +
                             " did not stop after PTRACE_ATTACH");
  }
  return true;
}

void attach_all_threads(pid_t pid, std::vector<pid_t>& attached,
                        const LogSink* log) {
  // A running target can create threads while we are attaching, so re-scan
  // until there is nothing new to attach.
  for (int round = 0; round < kMaxAttachRounds; ++round) {
    bool attached_anything = false;
    for (const pid_t tid : list_threads(pid)) {
      if (std::find(attached.begin(), attached.end(), tid) != attached.end()) {
        continue;
      }
      if (attach_one_thread(tid, attached)) {
        attached_anything = true;
      }
    }
    if (!attached_anything) {
      break;
    }
  }

  if (attached.empty()) {
    throw std::runtime_error("could not attach to any thread");
  }
  log_info(log, "attached to " + std::to_string(attached.size()) +
                    " thread(s) of pid " + std::to_string(pid));
}

void detach_all_threads(std::vector<pid_t>& attached, pid_t signal_tid,
                        int signal, const LogSink* log) {
  for (const pid_t tid : attached) {
    void* data = nullptr;
    if (tid == signal_tid && signal != 0) {
      data = reinterpret_cast<void*>(static_cast<intptr_t>(signal));
    }
    if (ptrace(PTRACE_DETACH, tid, nullptr, data) == -1 && errno != ESRCH) {
      const int err = errno;
      log_warn(log, "PTRACE_DETACH on tid " + std::to_string(tid) +
                        " failed: " + std::strerror(err));
    }
  }
  attached.clear();
}
